// Helper to filter items for a given level
export function getItemsForLevel(level: CareerLevel): AppraisalItem[] {
  if (level === 'EarlyYears') {
    return EARLY_YEARS_F2_ITEMS;
  }
  return PRIMARY_SECONDARY_F2_ITEMS.filter((item) => item.visibleFrom.includes(level));
}

// Calculate Section and Total Scores
export function calculateF2Scores(
  level: CareerLevel,
  scores: Record<string, { score: 1 | 2 | 3 | 4 | null }>
) {
  const items = getItemsForLevel(level);
  const config = LEVEL_SCORING_CONFIGS[level];

  let rawA = 0;
  let rawB = 0;
  let rawC = 0;
  let itemsScored = 0;

  items.forEach((item) => {
    const val = scores[item.id]?.score;
    if (val) {
      itemsScored++;
      if (item.section === 'A') rawA += val;
      else if (item.section === 'B') rawB += val;
      else if (item.section === 'C') rawC += val;
    }
  });

  const totalRaw = rawA + rawB + rawC;
  const percentage = (totalRaw / config.maxTotal) * 100;

  let grade: 'A' | 'B' | 'C' | 'D' | 'F' = 'F';
  if (totalRaw >= config.scaleA[0]) grade = 'A';
  else if (totalRaw >= config.scaleB[0]) grade = 'B';
  else if (totalRaw >= config.scaleC[0]) grade = 'C';
  else if (totalRaw >= config.scaleD[0]) grade = 'D';
  else grade = 'F';

  return {
    rawA,
    maxA: config.maxSectionA,
    rawB,
    maxB: config.maxSectionB,
    rawC,
    maxC: config.maxSectionC,
    totalRaw,
    maxTotal: config.maxTotal,
    percentage: Math.round(percentage * 10) / 10,
    grade,
    itemsScored,
    totalItems: items.length,
    isComplete: itemsScored === items.length,
  };
}

// Calculate Official Final Composite Score (F1, F2, F3, F4)
export function calculateCompositeScore(
  level: CareerLevel,
  f2RawScore: number,
  f2MaxScore: number,
  f1Percent: number = 85,
  f3Percent: number = 85,
  f4Percent: number = 80
) {
  const f2Percent = (f2RawScore / f2MaxScore) * 100;
  let composite = 0;

  if (level === 'EarlyYears') {
    // EY: F1 20% + F2 60% + F3 20% (F4 N/A)
    composite = f1Percent * 0.2 + f2Percent * 0.6 + f3Percent * 0.2;
  } else {
    // P&S: F1 20% + F2 50% + F3 20% + F4 10%
    composite = f1Percent * 0.2 + f2Percent * 0.5 + f3Percent * 0.2 + f4Percent * 0.1;
  }

  composite = Math.round(composite * 10) / 10;

  let predicate: 'Excellent' | 'Good' | 'Satisfactory' | 'Needs Improvement' | 'Unsatisfactory';
  let gradeLetter: 'A' | 'B' | 'C' | 'D' | 'F';

  if (composite >= 86) {
    predicate = 'Excellent';
    gradeLetter = 'A';
  } else if (composite >= 66) {
    predicate = 'Good';
    gradeLetter = 'B';
  } else if (composite >= 51) {
    predicate = 'Satisfactory';
    gradeLetter = 'C';
  } else if (composite >= 36) {
    predicate = 'Needs Improvement';
    gradeLetter = 'D';
  } else {
    predicate = 'Unsatisfactory';
    gradeLetter = 'F';
  }

  return {
    composite,
    predicate,
    gradeLetter,
    f1Percent,
    f2Percent: Math.round(f2Percent * 10) / 10,
    f3Percent,
    f4Percent: level === 'EarlyYears' ? null : f4Percent,
  };
}
